import { test, expect } from '@playwright/test';
test('lesson 15 separates local length, shared element writes and returned descriptor', async ({page}) => {
  await page.goto('/#lesson/15');
  await page.getByRole('button',{name:'动手观察',exact:true}).click();
  const lab = page.getByTestId('collections-lab-15');
  const state = async () => JSON.parse((await lab.getByTestId('live-model').getAttribute('data-state'))!);
  await lab.getByRole('button',{name:'单步：调用函数',exact:true}).click();
  await expect(lab.getByRole('button',{name:'验证：局部 append'})).toBeDisabled();
  await lab.getByLabel('调用结束后 len(cart)',{exact:true}).fill('1');
  await lab.getByLabel('调用结束后 cart[0]',{exact:true}).fill('9');
  await lab.getByLabel('预测依据',{exact:true}).fill('长度在局部描述符，共享数组首格会变');
  await lab.getByRole('button',{name:'验证：局部 append'}).click();
  expect(await state()).toMatchObject({caller:{len:1,array:'A'},local:{len:2,array:'A'},callerValues:[7]});
  await lab.getByRole('button',{name:'单步：已有元素写入'}).click();
  expect(await state()).toMatchObject({callerValues:[9],caller:{len:1}});
  await lab.getByRole('button',{name:'回退一步'}).click();
  expect(await state()).toMatchObject({callerValues:[7]});
  await lab.getByRole('button',{name:'单步：已有元素写入'}).click();
  await lab.getByRole('button',{name:'单步：函数返回'}).click();
  await lab.getByRole('button',{name:'单步：调用者处理结果'}).click();
  await expect(lab).toContainText('预测吻合');
  await lab.getByRole('button',{name:'修复：返回并接收，再观察'}).click();
  await lab.getByLabel('初始容量',{exact:true}).selectOption('1');
  await lab.getByLabel('调用结束后 len(cart)',{exact:true}).fill('2');
  await lab.getByLabel('调用结束后 cart[0]',{exact:true}).fill('9');
  await lab.getByLabel('预测依据',{exact:true}).fill('接收 B 的新描述符');
  for (const name of ['单步：调用函数','验证：局部 append','单步：已有元素写入','单步：函数返回','单步：调用者处理结果']) await lab.getByRole('button',{name,exact:true}).click();
  expect(await state()).toMatchObject({caller:{len:2,array:'B',cap:'≥ 2'},callerValues:[9,8]});
  await lab.getByRole('button',{name:'重置实验'}).click();
  expect(await state()).toMatchObject({phase:0,callerValues:[7]});
});
test('lesson 15 help links warehouse passes, descriptor reach, repairs and concealed transfer', async ({page}) => {
  await page.goto('/#lesson/15');
  await page.getByRole('button',{name:'动手观察',exact:true}).click();
  const help = page.getByTestId('collections-help-15');
  await page.getByRole('button',{name:'举例子',exact:true}).click();
  await help.getByRole('button',{name:'店员存入商品 8 并更新自己的证'}).click();
  await expect(help).toContainText('你的证：可见 1 格');
  await help.getByRole('button',{name:'接过店员的新证'}).click();
  await expect(help).toContainText('你的证：可见 2 格');
  await page.getByRole('button',{name:'画图',exact:true}).click();
  await help.getByLabel('这次追加前的容量').selectOption('1');
  await help.getByRole('button',{name:'追踪返回结果'}).click();
  expect(JSON.parse((await help.getByTestId('live-model').getAttribute('data-state'))!)).toMatchObject({selected:{array:'B',len:2}});
  await page.getByRole('button',{name:'拆步骤',exact:true}).click();
  await help.getByLabel('添加 return s 与 []int 返回类型',{exact:true}).check();
  for(let i=0;i<5;i++) await help.getByRole('button',{name:'执行下一条'}).click();
  await expect(help).toContainText('返回了 len=2，但 cart 仍 len=1');
  await help.getByLabel('调用处添加 cart =',{exact:true}).check();
  for(let i=0;i<5;i++) await help.getByRole('button',{name:'执行下一条'}).click();
  await expect(help).toContainText('修复达到目标');
  await page.getByRole('button',{name:'让我试试',exact:true}).click();
  const model = help.getByTestId('live-model');
  expect(JSON.parse((await model.getAttribute('data-state'))!)).not.toHaveProperty('result');
  await help.getByLabel('最终 len(items)',{exact:true}).fill('3');
  await help.getByLabel('推导理由',{exact:true}).fill('不接收缩短后的描述符');
  await help.getByRole('button',{name:'提交并核对'}).click();
  await expect(help).toContainText('本次独立提交吻合');
  await help.getByRole('button',{name:'换一个新情境'}).click();
  expect(JSON.parse((await model.getAttribute('data-state'))!)).not.toHaveProperty('result');
  await page.emulateMedia({reducedMotion:'reduce'});
  for (const width of [320,390]) {
    await page.setViewportSize({width,height:844});
    expect(await help.evaluate(e => e.scrollWidth <= e.clientWidth)).toBeTruthy();
    expect(await page.getByTestId('collections-lab-15').evaluate(e => e.scrollWidth <= e.clientWidth)).toBeTruthy();
  }
});
