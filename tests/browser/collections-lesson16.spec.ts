import { test, expect } from '@playwright/test';
test('lesson 16 zero length, repair, integer independence and rewind', async ({page}) => {
  await page.goto('/#lesson/16');
  await page.getByRole('button',{name:'动手观察',exact:true}).click();
  const lab = page.getByTestId('collections-lab-16');
  const model = lab.getByTestId('live-model');
  await expect(lab.getByRole('button',{name:'完成 copy 并核对'})).toBeDisabled();
  await lab.getByLabel('copy 将返回几项？',{exact:true}).fill('3');
  await lab.getByLabel('数量取决于什么？',{exact:true}).fill('先试容量是否决定复制数量');
  await lab.getByRole('button',{name:'完成 copy 并核对'}).click();
  expect(JSON.parse((await model.getAttribute('data-state'))!)).toMatchObject({returned:0,dst:[],capacity:3});
  await expect(lab).toContainText('数量预测需要修正');
  await lab.getByLabel('目标长度 len(dst)',{exact:true}).selectOption('3');
  await lab.getByLabel('目标容量 cap(dst)',{exact:true}).selectOption('6');
  await lab.getByLabel('copy 将返回几项？',{exact:true}).fill('3');
  await lab.getByLabel('数量取决于什么？',{exact:true}).fill('两边长度的最小值是 3，容量不参与');
  for (let i=0;i<3;i++) await lab.getByRole('button',{name:'单步复制一项'}).click();
  await lab.getByRole('button',{name:'完成 copy 并核对'}).click();
  await lab.getByRole('button',{name:'修改副本首项为 99'}).click();
  expect(JSON.parse((await model.getAttribute('data-state'))!)).toMatchObject({src:[3,6,9],dst:[99,6,9],returned:3});
  await lab.getByRole('button',{name:'回退一步'}).click();
  expect(JSON.parse((await model.getAttribute('data-state'))!)).toMatchObject({src:[3,6,9],dst:[3,6,9]});
  await lab.getByRole('button',{name:'重置实验'}).click();
  expect(JSON.parse((await model.getAttribute('data-state'))!)).toMatchObject({phase:0,dst:[],capacity:3});
});
test('lesson 16 help models support repair, references, overlap and concealed transfer', async ({page}) => {
  await page.goto('/#lesson/16');
  await page.getByRole('button',{name:'动手观察',exact:true}).click();
  const lab = page.getByTestId('collections-lab-16');
  const original = await lab.getByTestId('live-model').getAttribute('data-state');
  const help = page.getByTestId('collections-help-16');
  await page.getByRole('button',{name:'举例子',exact:true}).click();
  await help.getByLabel('已摆盒子数量',{exact:true}).selectOption('4');
  await help.getByRole('button',{name:'尝试复制四张卡'}).click();
  await expect(help).toContainText('目标达成');
  await page.getByRole('button',{name:'画图',exact:true}).click();
  await help.getByRole('button',{name:'执行 *dst[0] = 99',exact:true}).click();
  expect(JSON.parse((await help.getByTestId('live-model').getAttribute('data-state'))!)).toMatchObject({objects:{X:99}});
  await help.getByRole('button',{name:'执行 dst[0] = &Z',exact:true}).click();
  expect(JSON.parse((await help.getByTestId('live-model').getAttribute('data-state'))!)).toMatchObject({src:['X','Y'],dst:['Z','Y'],objects:{X:3}});
  await page.getByRole('button',{name:'拆步骤',exact:true}).click();
  for(let i=0;i<3;i++) await help.getByRole('button',{name:'展开下一项映射'}).click();
  expect(JSON.parse((await help.getByTestId('live-model').getAttribute('data-state'))!)).toMatchObject({array:[2,2,4,6]});
  await page.getByRole('button',{name:'让我试试',exact:true}).click();
  expect(JSON.parse((await help.getByTestId('live-model').getAttribute('data-state'))!)).not.toHaveProperty('result');
  await expect(help.getByRole('button',{name:'提交并核对'})).toBeDisabled();
  await help.getByLabel('返回值 n',{exact:true}).fill('2');
  await help.getByLabel('解释长度与容量的作用',{exact:true}).fill('目标长度限制为 2，容量 7 无关');
  await help.getByRole('button',{name:'提交并核对'}).click();
  await expect(help).toContainText('本次预测吻合');
  await expect(lab.getByTestId('live-model')).toHaveAttribute('data-state',original!);
  await page.emulateMedia({reducedMotion:'reduce'});
  for(const width of [390,320]) {
    await page.setViewportSize({width,height:844});
    expect(await lab.evaluate(e => e.scrollWidth <= e.clientWidth)).toBeTruthy();
    expect(await help.evaluate(e => e.scrollWidth <= e.clientWidth)).toBeTruthy();
  }
  await help.getByRole('button',{name:'换一组输入'}).focus();
  await page.keyboard.press('Enter');
  expect(JSON.parse((await help.getByTestId('live-model').getAttribute('data-state'))!)).toMatchObject({variant:1,checked:false});
});
