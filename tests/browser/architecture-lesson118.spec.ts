import { test, expect, type Locator, type Page } from '@playwright/test';
async function open(page: Page) { await page.goto('/#lesson/118'); await page.getByRole('button', { name: '动手观察', exact: true }).click(); const lab = page.getByTestId('architecture-lab-118'); await expect(lab).toBeVisible(); return lab; }
async function step(lab: Locator, count = 1) { for (let i = 0; i < count; i++) await lab.locator('[data-arch-action=step]').click(); }
async function help(page: Page, mode: string) { await page.locator('.help-panel').getByRole('button', { name: mode, exact: true }).click(); const panel = page.getByTestId('architecture-help-118'); await expect(panel).toBeVisible(); return panel; }
test('118 offline completion, authorized recovery, independent download permission and expiration are visible', async ({ page }) => {
  const lab = await open(page); await step(lab, 2);
  await expect(lab.getByTestId('status-server')).toHaveText('处理中');
  await expect(lab.getByTestId('status-client')).toHaveText('已接收');
  await lab.getByRole('button', { name: '关闭页面', exact: true }).click(); await step(lab, 3);
  await expect(lab.getByTestId('status-server')).toHaveText('成功');
  await expect(lab.getByTestId('status-channel')).toHaveText('通知已丢失');
  await lab.getByRole('button', { name: '重新打开页面', exact: true }).click();
  await expect(lab.getByTestId('status-client')).toHaveText('当前结果未知');
  await lab.getByRole('button', { name: '查询任务状态', exact: true }).click();
  await expect(lab.getByTestId('status-client')).toHaveText('成功');
  await lab.getByLabel('当前访问身份').selectOption('other');
  await lab.getByRole('button', { name: '查询任务状态', exact: true }).click();
  await expect(lab.locator('.arch118-feedback')).toContainText('403');
  await lab.getByRole('button', { name: '获取结果', exact: true }).click();
  await expect(lab.getByTestId('local-result')).toHaveText('本地副本：尚未取得');
  await lab.getByLabel('当前访问身份').selectOption('owner');
  await lab.getByRole('button', { name: '获取结果', exact: true }).click();
  await expect(lab.getByTestId('local-result')).toHaveText('本地副本：已取得');
  await lab.getByRole('button', { name: '显式取消任务', exact: true }).click();
  await expect(lab.getByTestId('status-server')).toHaveText('成功');
  await step(lab, 2); await expect(lab.getByTestId('status-server')).toHaveText('结果已过期');
  await lab.getByRole('button', { name: '获取结果', exact: true }).click();
  await expect(lab.locator('.arch118-feedback')).toContainText('410');
  await expect(lab.getByTestId('local-result')).toHaveText('本地副本：已取得');
});
test('118 explicit early cancellation, failure and short synchronous success produce distinct outcomes', async ({ page }) => {
  const lab = await open(page); await step(lab, 2);
  await lab.getByRole('button', { name: '显式取消任务', exact: true }).click();
  await expect(lab.getByTestId('status-server')).toHaveText('已取消'); await expect(lab.locator('[data-arch-action=step]')).toBeDisabled();
  await lab.locator('[data-arch-action=reset]').click(); await step(lab, 2);
  await lab.getByRole('button', { name: '注入后台失败', exact: true }).click();
  await expect(lab.getByTestId('status-server')).toHaveText('失败');
  await lab.getByLabel('交互方案').selectOption('sync'); await lab.getByLabel('后台工作量').selectOption('1'); await step(lab, 3);
  await expect(lab.getByTestId('status-client')).toHaveText('成功'); await expect(lab.getByTestId('local-result')).toHaveText('本地副本：已取得');
  await lab.getByLabel('后台工作量').selectOption('3'); await step(lab, 5);
  await expect(lab.getByTestId('status-server')).toHaveText('成功'); await expect(lab.getByTestId('status-client')).toHaveText('当前结果未知');
});
