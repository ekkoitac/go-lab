import { test, expect } from '@playwright/test';
for (const width of [1440, 390]) test(`72 PATCH prediction, revision, comparison and help at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 1000 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const formal: string[] = [];
  page.on('request', r => { if (r.method() === 'POST' && /\/progress\/72\/(attempt|reveal)$/.test(r.url())) formal.push(r.url()); });
  await page.goto('/#lesson/72');
  await page.getByRole('button', { name: '动手观察', exact: true }).click();
  const lab = page.getByTestId('data-boundary-lab-72'), model = lab.getByTestId('live-model');
  await expect(lab).toBeVisible();
  const editor = await page.locator('.cm-content').first().textContent();
  await expect(lab.locator('[data-action=step]')).toBeDisabled();
  await lab.getByLabel('预测最终额度').selectOption('keep');
  await lab.getByLabel('预测理由').fill('缺失应当保留，但需要检验普通字段是否记录存在性');
  await lab.locator('[data-action=step]').focus(); await page.keyboard.press('Enter');
  await lab.locator('[data-action=step]').click(); await lab.locator('[data-action=step]').click();
  expect(JSON.parse((await model.getAttribute('data-state'))!).result).toBe(0);
  await expect(model.locator('[data-result="0"]')).toBeVisible();
  await expect(lab.getByText('预测需要修正：0', { exact: true })).toBeVisible();
  await lab.getByLabel('根据证据修正解释').fill('新 int 为零，直接覆盖导致未提供字段被误更新。');
  await lab.getByRole('button', { name: '保存当前结果为基线', exact: true }).click();
  await lab.locator('[data-action=back]').click();
  expect(JSON.parse((await model.getAttribute('data-state'))!).applied).toBe(false);
  await lab.locator('[data-action=step]').click();
  expect(JSON.parse((await model.getAttribute('data-state'))!).result).toBe(0);
  await lab.getByRole('button', { name: '自由实验', exact: true }).click();
  await lab.getByLabel('接收与更新策略').selectOption('presence');
  for (let i = 0; i < 3; i++) await lab.locator('[data-action=step]').click();
  expect(JSON.parse((await model.getAttribute('data-state'))!).result).toBe(100);
  await expect(lab.getByText('基线结果：0 ｜ 本轮：100', { exact: true })).toBeVisible();
  await lab.getByLabel('请求字段').selectOption('null');
  expect(JSON.parse((await model.getAttribute('data-state'))!).decoded).toBeNull();
  await lab.getByRole('button', { name: '引导任务', exact: true }).click();
  await expect(lab.getByLabel('预测最终额度')).toHaveValue('');
  await expect(lab.locator('[data-action=step]')).toBeDisabled();
  await page.locator('.help-panel').getByRole('button', { name: '三种更新指令', exact: true }).click();
  let help = page.getByTestId('data-boundary-help-72');
  await help.getByLabel('选择请求').selectOption('null');
  await help.getByRole('button', { name: '清除', exact: true }).click();
  await help.getByRole('button', { name: '核对连接', exact: true }).click();
  expect(JSON.parse((await help.getByTestId('live-model').getAttribute('data-state'))!).result).toBeNull();
  await page.locator('.help-panel').getByRole('button', { name: '追踪一次更新', exact: true }).click();
  help = page.getByTestId('data-boundary-help-72');
  await help.getByLabel('共同初始化').selectOption('reuse');
  for (let i = 0; i < 3; i++) await help.getByRole('button', { name: '推进共同步骤', exact: true }).click();
  const states = await help.getByTestId('live-model').evaluateAll(ns => ns.map(n => JSON.parse(n.getAttribute('data-state')!)));
  expect(states.map(s => s.result)).toEqual([100, 100, null]);
  await page.locator('.help-panel').getByRole('button', { name: '保住未修改字段', exact: true }).click();
  help = page.getByTestId('data-boundary-help-72');
  await expect(help.getByTestId('live-model')).toHaveCount(0);
  await help.getByLabel('修复依据').fill('先对照普通字段，再找需要补充的存在性信息');
  await help.getByRole('button', { name: '验证三个请求', exact: true }).click();
  await expect(help.getByText(/首次未提示提交：需修正/)).toBeVisible();
  await help.getByRole('button', { name: '查看提示', exact: true }).click();
  await help.getByLabel('修复策略').selectOption('presence');
  await help.getByRole('button', { name: '验证三个请求', exact: true }).click();
  await expect(help.getByText('三个请求全部符合约定。', { exact: true })).toBeVisible();
  await expect(help.getByText(/首次未提示提交：需修正/)).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(await page.locator('.cm-content').first().textContent()).toBe(editor);
  expect(formal).toEqual([]);
});
